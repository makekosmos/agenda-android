#!/usr/bin/env python3
"""Regenerate ZeronThemes.kt from zeron's crates/theme/src/builtins.rs.

usage: gen_zeron_themes.py <zeron checkout> [rev]   (rev defaults to origin/main)
"""
import re
import subprocess
import sys
from pathlib import Path

FIELDS = ["background", "shell", "raised", "card", "text", "muted", "faint",
          "accent", "danger", "warning", "success"]

zeron, rev = sys.argv[1], (sys.argv[2] if len(sys.argv) > 2 else "origin/main")
git = lambda *a: subprocess.check_output(["git", "-C", zeron, *a], text=True)
sha = git("rev-parse", "--short", rev).strip()
src = git("show", f"{rev}:crates/theme/src/builtins.rs")

fn_seeds = {}
for m in re.finditer(r"fn (\w+)\(\) -> ThemeVariant \{\s*variant\(Seeds \{(.*?)\n\s*source:", src, re.S):
    body = m.group(2)
    get = lambda k: re.search(rf'\b{k}: "([^"]*)"', body).group(1)
    seed = {k: get(k) for k in ["id", "name", *FIELDS]}
    seed["dark"] = "Appearance::Dark" in body
    fn_seeds[m.group(1)] = seed

registry = src[src.index("families: vec!["):src.index("fn family(")]
families = [
    (fid, name, re.findall(r"(\w+)\(\)", variants))
    for fid, name, variants in re.findall(r'family\(\s*"([^"]+)",\s*"([^"]+)",\s*vec!\[([^\]]*)\]', registry)
]

hex_ = lambda h: f"0x{h.lstrip('#').upper()}"
out = [
    "// Generated by tools/gen_zeron_themes.py from zeron",
    f"// crates/theme/src/builtins.rs @ {sha}. Do not edit by hand.",
    "package com.mundus.agenda.ui",
    "",
    "val ZeronFamilies: List<ZeronFamily> =",
    "    listOf(",
]
for fid, name, fns in families:
    out.append(f'        ZeronFamily("{fid}", "{name}", listOf(')
    for fn in fns:
        s = fn_seeds[fn]
        cols = ", ".join(f"{k} = {hex_(s[k])}" for k in FIELDS)
        out.append(f'            ZeronSeed("{s["id"]}", "{s["name"]}", dark = {str(s["dark"]).lower()}, {cols}),')
    out.append("        )),")
out += ["    )", ""]

dest = Path(__file__).resolve().parent.parent / "app/src/main/java/com/mundus/agenda/ui/ZeronThemes.kt"
dest.write_text("\n".join(out))
print(f"{len(families)} families, {sum(len(f[2]) for f in families)} variants @ {sha} -> {dest}")
