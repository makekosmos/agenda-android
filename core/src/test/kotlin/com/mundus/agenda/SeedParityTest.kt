package com.mundus.agenda

import java.nio.file.Files
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import kotlinx.coroutines.withTimeout
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.put
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Gate A (KOS-370 Phase 1): loads the golden dump produced by
 * `cargo run -p agenda-core --bin seed-parity` in the desktop worktree
 * (committed as `parity-golden.json`, regenerated by
 * `scripts/parity-golden.sh`), upserts every engine object into a real
 * host `MobileEngine`, then collects the production `boardFlow()` and
 * asserts the repository-produced smart lists, project views, tag
 * filters, project/tag metadata and Logbook archived projects match the
 * ids agenda-core computed — the exact path the app renders.
 */
class SeedParityTest {
    private val json = Json { ignoreUnknownKeys = true }

    @Test
    fun seedParity() = runBlocking {
        val golden =
            json.parseToJsonElement(
                    SeedParityTest::class.java.getResource("/parity-golden.json")!!.readText()
                )
                .jsonObject

        val (repository, dataDir) = seededRepository(json, golden)
        try {
            repository.use { repository ->
                val state = withTimeout(15_000) { repository.boardFlow().first() }
                val board =
                    (state as? BoardState.Ready)?.board
                        ?: throw AssertionError("boardFlow emitted $state, expected Ready")

                val expected = golden["expected"]!!.jsonObject
                val lists = expected["lists"]!!.jsonObject
                fun expectList(key: String) =
                    lists[key]!!.jsonArray.map { it.jsonPrimitive.content }
                fun ids(tasks: List<Task>) = tasks.map { it.id }

                assertEquals(expectList("inbox"), ids(board.list(SmartList.INBOX)))
                assertEquals(expectList("week"), ids(board.list(SmartList.WEEK)))
                assertEquals(expectList("nextWeek"), ids(board.list(SmartList.NEXT_WEEK)))
                assertEquals(expectList("someday"), ids(board.list(SmartList.SOMEDAY)))
                assertEquals(expectList("logbook"), ids(board.list(SmartList.LOGBOOK)))
                assertEquals(expectList("trash"), ids(board.list(SmartList.TRASH)))

                for ((projectId, want) in expected["projects"]!!.jsonObject) {
                    assertEquals(
                        "project $projectId",
                        want.jsonArray.map { it.jsonPrimitive.content },
                        ids(board.projectTasks[projectId].orEmpty()),
                    )
                }
                // Project/tag metadata the UI renders: live projects in
                // sort order, archived (status 2) projects for the Logbook
                // «Проекты» section, and the shared tag list.
                assertEquals(
                    golden["projects"]!!.jsonArray.map { it.jsonObject["id"]!!.jsonPrimitive.content },
                    board.projects.map { it.id },
                )
                assertEquals(
                    expected["logbookProjects"]!!.jsonArray.map { it.jsonPrimitive.content },
                    board.projects.filter { it.status == 2 }.map { it.id },
                )
                assertEquals(
                    golden["tags"]!!.jsonArray.map { it.jsonObject["id"]!!.jsonPrimitive.content },
                    board.tags.map { it.id },
                )

                // Date views cover every dated task.
                for (todo in golden["todos"]!!.jsonArray) {
                    val id = todo.jsonObject["id"]!!.jsonPrimitive.content
                    val wantsDate =
                        todo.jsonObject["scheduled_date"]?.jsonPrimitive?.content != null ||
                            todo.jsonObject["deadline"]?.jsonPrimitive?.content != null
                    if (wantsDate) {
                        assertTrue("no dateView for $id", board.dateViews.containsKey(id))
                    }
                }
            }
        } finally {
            java.io.File(dataDir).deleteRecursively()
        }
    }
}
