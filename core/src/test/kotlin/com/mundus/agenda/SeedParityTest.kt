package com.mundus.agenda

import java.nio.file.Files
import kotlinx.coroutines.runBlocking
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.put
import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * Gate A (KOS-370 Phase 1): loads the golden dump produced by
 * `cargo run -p agenda-core --bin seed-parity` in the desktop worktree
 * (committed as `parity-golden.json`, regenerated by
 * `scripts/parity-golden.sh`), upserts every engine object into a real
 * host `MobileEngine`, reads everything back through the same UniFFI
 * exports the app uses, and asserts each smart list, project view and tag
 * filter returns exactly the ids agenda-core computed.
 */
class SeedParityTest {
    private val json = Json { ignoreUnknownKeys = true }

    @Test
    fun seedParity() = runBlocking {
        val golden =
            json.parseToJsonElement(
                    SeedParityTest::class.java.getResource("/parity-golden.json")!!.readText()
                )
                .jsonObject
        val today = golden["today"]!!.jsonPrimitive.content
        val offset = golden["utcOffsetSeconds"]!!.jsonPrimitive.content.toInt()

        val dataDir = Files.createTempDirectory("agenda-parity-test").toString()
        EngineAgendaRepository(dataDir).use { repository ->
            // `com.kosmos.agenda.references` is a non-canonical type the
            // desktop DB carries from before the canonical registry; a
            // fresh phone DB must register it before upsert.
            repository.call(
                "upsert_object_type",
                buildJsonObject {
                    put(
                        "object_type",
                        buildJsonObject {
                            put("id", "com.kosmos.agenda.references")
                            put("name", "Agenda references")
                            put("schemaJson", "{}")
                            put("uiSchemaJson", "{}")
                            put("createdAt", golden["today"]!!.jsonPrimitive.content)
                            put("updatedAt", golden["today"]!!.jsonPrimitive.content)
                            put("systemLocked", false)
                        },
                    )
                },
            )
            for (obj in golden["objects"]!!.jsonArray) {
                try {
                    repository.call("upsert_object", buildJsonObject { put("object", obj) })
                } catch (e: IllegalStateException) {
                    throw AssertionError("upsert failed for ${obj.jsonObject["id"]}: ${e.message}")
                }
            }
            println("types: " + repository.call("list_object_types", buildJsonObject {}))

            val todoJsons = repository.todoJsons()
            val todosJson = "[${todoJsons.joinToString(",")}]"
            val ids = todoJsons.map { json.parseToJsonElement(it).jsonObject["id"]!!.jsonPrimitive.content }

            val expected = golden["expected"]!!.jsonObject
            val lists = expected["lists"]!!.jsonObject
            fun expect(key: String): List<String> =
                lists[key]!!.jsonArray.map { it.jsonPrimitive.content }

            fun idsOf(indices: List<UInt>) = indices.map { ids[it.toInt()] }

            assertEquals(expect("inbox"), idsOf(smartListIndices(SmartListName.INBOX, todosJson, today, offset)))
            assertEquals(expect("today"), idsOf(todayListIndices(todosJson, today, offset)))
            assertEquals(expect("week"), idsOf(smartListIndices(SmartListName.WEEK, todosJson, today, offset)))
            assertEquals(expect("nextWeek"), idsOf(smartListIndices(SmartListName.NEXT_WEEK, todosJson, today, offset)))
            assertEquals(expect("someday"), idsOf(smartListIndices(SmartListName.SOMEDAY, todosJson, today, offset)))
            assertEquals(expect("logbook"), idsOf(smartListIndices(SmartListName.LOGBOOK, todosJson, today, offset)))
            assertEquals(expect("trash"), idsOf(smartListIndices(SmartListName.TRASH, todosJson, today, offset)))

            for ((projectId, want) in expected["projects"]!!.jsonObject) {
                assertEquals(
                    "project $projectId",
                    want.jsonArray.map { it.jsonPrimitive.content },
                    idsOf(projectTaskIndices(projectId, todosJson, today, offset)),
                )
            }
            for ((tagId, want) in expected["tags"]!!.jsonObject) {
                assertEquals(
                    "tag $tagId",
                    want.jsonArray.map { it.jsonPrimitive.content },
                    idsOf(tagTaskIndices(tagId, todosJson)),
                )
            }

            // Field fidelity: every todo read back through
            // taskFromEngineObject carries the seeded title and id set.
            assertEquals(
                golden["todos"]!!.jsonArray.map { it.jsonObject["id"]!!.jsonPrimitive.content }.toSet(),
                ids.toSet(),
            )
        }
    }
}
